#!/usr/bin/env node
/**
 * Non-destructive local environment bootstrap: generates a `.env` with
 * random local secrets. Never overwrites an existing `.env` (docs/OPERATIONS.md).
 * This single file is read both by the app (`--env-file=.env`) and by
 * `docker compose` (auto-loaded for ${VAR} substitution in compose.yaml).
 */
import { existsSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import { randomAlphanumeric, randomHex } from './lib/secrets.mjs'

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const envPath = path.join(rootDir, '.env')

if (existsSync(envPath)) {
  console.log(`.env already exists at ${envPath} — leaving it untouched.`)
  console.log('Delete it manually first if you really want a fresh set of local secrets.')
  process.exit(0)
}

const postgresUser = 'hasan'
const postgresPassword = randomAlphanumeric(32)
const postgresDb = 'hasan_journal'

const s3AccessKeyId = randomAlphanumeric(20)
const s3SecretAccessKey = randomAlphanumeric(40)
const s3Bucket = 'hasan-journal-media'
const garageRpcSecret = randomHex(32)

const payloadSecret = randomHex(48)

const env = `# Generated by \`pnpm setup:local\` on ${new Date().toISOString()}.
# Local development only — do not commit, do not reuse in production.
# See .env.example for the full contract and docker-hostname notes.

NODE_ENV=development
PUBLIC_SITE_URL=http://localhost:3000
PORT=3000
PAYLOAD_SECRET=${payloadSecret}

# --- PostgreSQL --------------------------------------------------------
POSTGRES_USER=${postgresUser}
POSTGRES_PASSWORD=${postgresPassword}
POSTGRES_DB=${postgresDb}
DATABASE_URI=postgres://${postgresUser}:${postgresPassword}@localhost:5432/${postgresDb}

# --- Garage (S3-compatible storage, see docs/DECISIONS.md) ------------
GARAGE_RPC_SECRET=${garageRpcSecret}
GARAGE_ACCESS_KEY_ID=${s3AccessKeyId}
GARAGE_SECRET_ACCESS_KEY=${s3SecretAccessKey}
GARAGE_BUCKET=${s3Bucket}

S3_ENDPOINT=http://localhost:3900
S3_REGION=garage
S3_BUCKET=${s3Bucket}
S3_ACCESS_KEY_ID=${s3AccessKeyId}
S3_SECRET_ACCESS_KEY=${s3SecretAccessKey}
S3_FORCE_PATH_STYLE=true

# --- Mailpit (local mail capture, see docs/DECISIONS.md) --------------
SMTP_HOST=localhost
SMTP_PORT=1025
SMTP_SECURE=false
SMTP_USER=
SMTP_PASS=
SMTP_FROM_ADDRESS=no-reply@localhost
SMTP_FROM_NAME=Hasan Journal

# --- Local-only test fixtures ------------------------------------------
ALLOW_DEMO_SEED=false
`

writeFileSync(envPath, env, { mode: 0o600 })
console.log(`Wrote ${envPath} with fresh random local secrets.`)
console.log('Next: pnpm services:up   (start Postgres, Garage, Mailpit)')
console.log('Then: pnpm db:migrate && pnpm admin:bootstrap && pnpm seed')
