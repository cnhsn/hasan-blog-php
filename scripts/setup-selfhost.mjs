#!/usr/bin/env node
/**
 * Generates `.env.selfhost` for the fully self-contained Docker
 * deployment (compose.selfhost.yaml) with its own fresh secrets —
 * deliberately not shared with the development `.env`.
 *
 * Non-destructive: refuses to overwrite an existing file.
 */
import { existsSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import { randomAlphanumeric, randomHex } from './lib/secrets.mjs'

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const envPath = path.join(rootDir, '.env.selfhost')

if (existsSync(envPath)) {
  console.log(`.env.selfhost already exists — leaving it untouched.`)
  console.log('Delete it manually first if you really want new secrets (this orphans existing data).')
  process.exit(0)
}

const appPort = process.env.APP_PORT ?? '8080'
const mailpitPort = process.env.MAILPIT_UI_PORT ?? '8026'

const env = `# Generated by \`node scripts/setup-selfhost.mjs\` on ${new Date().toISOString()}.
# Secrets for the self-hosted Docker deployment (compose.selfhost.yaml).
# Separate from .env, which is for local development. Never commit this file.

APP_PORT=${appPort}
MAILPIT_UI_PORT=${mailpitPort}
PUBLIC_SITE_URL=http://localhost:${appPort}

PAYLOAD_SECRET=${randomHex(48)}

POSTGRES_USER=hasan
POSTGRES_PASSWORD=${randomAlphanumeric(32)}
POSTGRES_DB=hasan_journal

GARAGE_RPC_SECRET=${randomHex(32)}
GARAGE_ACCESS_KEY_ID=${randomAlphanumeric(20)}
GARAGE_SECRET_ACCESS_KEY=${randomAlphanumeric(40)}
GARAGE_BUCKET=hasan-journal-media

SMTP_FROM_ADDRESS=no-reply@localhost
SMTP_FROM_NAME=Hasan Journal
`

writeFileSync(envPath, env, { mode: 0o600 })
console.log(`Wrote ${path.relative(rootDir, envPath)} with fresh secrets (mode 600).`)
console.log(`Site will be served at http://localhost:${appPort}`)
